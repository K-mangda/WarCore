import ts from 'typescript';
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const out=resolve('.local-evidence/resume-check');mkdirSync(out,{recursive:true});
for(const name of ['Input','PointerLockState','ControlPreferences'])writeFileSync(resolve(out,name+'.mjs'),ts.transpileModule(readFileSync('src/core/'+name+'.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText.replace(/from '(\.[^']+)'/g,"from '$1.mjs'"));
const {PointerLockState}=await import(pathToFileURL(resolve(out,'PointerLockState.mjs')));
const lock=new PointerLockState();assert.equal(lock.changed(true),false);
lock.release();assert.equal(lock.changed(false),false,'Delayed intentional unlock must not pause resumed gameplay');
assert.equal(lock.changed(false),false,'Rejected pointer-lock fallback remains playable');
lock.changed(true);assert.equal(lock.changed(false),true,'User Escape still pauses gameplay');
const listeners=new Map();globalThis.window={addEventListener(type,fn){listeners.set(type,fn);},removeEventListener(type){listeners.delete(type);}};
const {Input}=await import(pathToFileURL(resolve(out,'Input.mjs')));let active=true,paused=0;const input=new Input(()=>active,()=>paused++);
const event=code=>({code,repeat:false,preventDefault(){}});
listeners.get('keydown')(event('KeyW'));assert.ok(input.keys.has('KeyW'));
active=false;input.clear();assert.equal(input.keys.size,0);
active=true;input.resume();assert.ok(input.keys.has('KeyW'),'Held movement resumes after the upgrade modal');
listeners.get('keyup')(event('KeyW'));assert.equal(input.keys.size,0);
listeners.get('keydown')(event('KeyD'));listeners.get('blur')();input.resume();assert.equal(input.keys.size,0,'Focus loss must not restore stale held keys');
listeners.get('keydown')(event('Escape'));assert.equal(paused,1);
input.dispose();assert.equal(listeners.size,0);
console.log('Resume checks passed: delayed pointer unlock, drag fallback, Escape, held movement, focus loss and cleanup.');
