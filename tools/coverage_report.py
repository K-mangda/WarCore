"""Coverage of the decompile plan against all game classes in dump.cs. Usage: python -I tools/coverage_report.py <out.md>"""
import re,sys,json
txt=open(r'C:\Users\Korawit\Desktop\megabonk_decompiled\dump.cs',encoding='utf-8',errors='ignore').read()
parts=re.split(r'\n(?=(?:public |internal |private )?(?:sealed |abstract |static )*(?:class|struct) )',txt)
classes={}
for p in parts:
    m=re.match(r'(?:public |internal |private )?(?:sealed |abstract |static )*(?:class|struct) (\w+)',p)
    if not m:continue
    n=len(re.findall(r'// RVA: 0x',p));t=re.search(r'TypeDefIndex: (\d+)',p)
    if n and t and 4606<=int(t.group(1))<5827:classes[m.group(1)]=n  # Assembly-CSharp.dll type range from the dump header
plan=json.load(open('.local-evidence/decompile6-plan-final.json'))
covered=set()
for x in plan:
    m=re.match(r'(?:weapon|tome|enemy|interact|item)__(\w+?)\.',x['label'])
    if m:covered.add(m.group(1))
uncovered={c:n for c,n in classes.items() if c not in covered}
game=list(uncovered)
out=['# Decompile coverage (generated by tools/coverage_report.py)','',f'- Classes with methods in dump.cs: {len(classes)} ({sum(classes.values())} methods)',f'- Classes in the current decompile plan: {len(covered)}',f'- Not in the plan: {len(uncovered)} classes; likely game classes among them: {len(game)}','','## Not covered, largest first (top 150)','','| Class | Methods |','|---|---|']
for c in sorted(game,key=lambda c:-uncovered[c])[:150]:out.append(f'| {c} | {uncovered[c]} |')
open(sys.argv[1],'w',encoding='utf-8').write('\n'.join(out)+'\n')
print(len(classes),len(covered),len(uncovered),len(game))
