"""Copy the real icons of characters, weapons, Tomes, items, hats and shop items from the Unity dump into public/ui/icons/.
Icons are found through the `icon` field of each ScriptableObject (CharacterData, WeaponData, TomeData, ItemData, HatData, ShopItemData)
via unity-dump/asset-index.json (built by tools/build_asset_index.py). Writes src/data/Icons.ts (name -> url) and public/ui/icons/provenance.json.
Usage: python -I tools/export_icons.py"""
import json,shutil,hashlib,re
from pathlib import Path
dump=Path('.local-evidence/unity-dump');out=Path('public/ui/icons');out.mkdir(parents=True,exist_ok=True)
index=json.loads((dump/'asset-index.json').read_text(encoding='utf-8'))
kinds={'CharacterData':'characters','WeaponData':'weapons','TomeData':'tomes','ItemData':'items','HatData':'hats','ShopItemData':'shop','PassiveData':'passives','SkinData':'skins'}
icons={k:{} for k in kinds.values()};prov={}
safe=lambda s:re.sub(r'[^\w-]','_',s)
for key,tex in index.items():
    for use in tex['usedBy']:
        if use.get('by')!='script-field' or use.get('class') not in kinds or not str(use.get('field','')).startswith('icon'):continue
        if not tex.get('png'):continue
        kind=kinds[use['class']];name=use.get('object') or tex['name']
        if name in icons[kind]:continue
        target=out/kind/f'{safe(name)}.png';target.parent.mkdir(parents=True,exist_ok=True)
        shutil.copyfile(dump/tex['png'],target)
        icons[kind][name]=f'ui/icons/{kind}/{target.name}'
        prov[f'{kind}/{target.name}']={'source':key,'texture':tex['name'],'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'filter':tex.get('filter')}
(out/'provenance.json').write_text(json.dumps({'from':'Megabonk_Data via tools/dump_all_unity.py + tools/export_icons.py','files':prov},indent=1),encoding='utf-8')
ts='// Generated by tools/export_icons.py from the game data: ScriptableObject name -> icon url (public/ui/icons). Do not edit.\n'
ts+='export const gameIcons='+json.dumps(icons,indent=1)+' as const;\n'
Path('src/data/Icons.ts').write_text(ts,encoding='utf-8')
print({k:len(v) for k,v in icons.items()})
